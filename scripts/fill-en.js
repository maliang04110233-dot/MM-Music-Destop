// ── 应用规则 ──────────────────────────────
function translateZhToEn(text) {
  let result = text;
  for (const [zh, enText] of RULES) {
    result = result.split(zh).join(enText);
  }
  return result;
}

// ── 主逻辑 ────────────────────────────────
let added = 0;
const keys = Object.keys(zh);

for (const key of keys) {
  if (en[key] === undefined) {
    en[key] = translateZhToEn(zh[key]);
    added++;
  }
}

fs.writeFileSync(EN_PATH, JSON.stringify(en, null, 2) + '\n');
console.log(`Added ${added} missing translations to en.json`);
console.log(`en.json now: ${Object.keys(en).length} entries (was ${Object.keys(en).length - added})`);